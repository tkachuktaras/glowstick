# Version: from a vX.Y.Z tag (a release in CI), otherwise from the VERSION file
function Get-AppVersion {
    if ($env:GITHUB_REF_TYPE -eq 'tag' -and $env:GITHUB_REF_NAME -match '^v(\d+\.\d+\.\d+)$') { return $Matches[1] }
    return (Get-Content (Join-Path $root 'VERSION') -Raw).Trim()
}

# GitHub repository (owner/name) for the update check: from CI or git remote origin; not found — ''
function Get-Repo {
    if ($env:GITHUB_REPOSITORY) { return $env:GITHUB_REPOSITORY }
    try {
        $url = (& git -C $root remote get-url origin 2>$null)
        if ($url -match 'github\.com[:/]([^/]+/[^/]+?)(\.git)?/?$') { return $Matches[1] }
    } catch { }
    return ''
}

# obj\BuildInfo.cs — version and repository filled in at build time
function New-BuildInfo([string]$repo) {
    $obj = Join-Path $root 'obj'
    New-Item -ItemType Directory -Force $obj | Out-Null
    $ver = Get-AppVersion
    $path = Join-Path $obj 'BuildInfo.cs'
    @"
// Generated by build.ps1 — do not edit.
[assembly: System.Reflection.AssemblyVersion("$ver.0")]
[assembly: System.Reflection.AssemblyFileVersion("$ver.0")]
[assembly: System.Reflection.AssemblyInformationalVersion("$ver")]
namespace Glowstick { static class BuildInfo { public const string Repo = "$repo"; } }
"@ | Set-Content -Encoding UTF8 $path
    return $path
}

